# ── Paste-back blend mode ───────────────────────────────────────────────────
#   normal  Poisson NORMAL_CLONE. Hides the seam and adopts the user's
#           lighting, but the swapped face's OWN gradients are what get
#           reconstructed — so the uploaded identity survives. Default.
#   mixed   Poisson MIXED_CLONE. Keeps whichever gradient is stronger, which
#           in practice means the user's real brows/eye-creases/nose edges
#           ghost back through the swap. Looks "half you, half them" — this
#           was the old default and the main reason the mask read as wrong.
#   alpha   Feathered alpha blend, no Poisson (roop / Deep-Live-Cam default).
#           Strongest identity and the cheapest of the three (~8 ms saved per
#           frame), at the cost of a slightly more visible edge in hard light.
_CLONE_MODE     = os.environ.get("LUCY_CLONE_MODE", "normal").strip().lower()


async def _get_session(session_id: str) -> dict:
    """Return (creating if needed) the session struct for `session_id`."""
    async with _SESSIONS_LOCK:
        s = _SESSIONS.get(session_id)
        if s is None:
            s = {
                "audio_buf":      np.zeros(0, dtype=np.float32),
                "audio_t_ms":     0,             # cumulative pitch-shifted audio output time
                "last_frame":     None,          # most recent swapped frame BGR np.uint8
                "last_face":      None,          # most recent tgt_face object
                "lipsync_every":  2,             # run Wav2Lip every Nth swap frame
                "frame_counter":  0,
            }
            _SESSIONS[session_id] = s
        return s


async def _release_session(session_id: str, key: str) -> None:
    """Drop a session entry once both endpoints have released their hold."""
    async with _SESSIONS_LOCK:
        s = _SESSIONS.get(session_id)
        if s is None:
            return
        s.pop(key, None)
        # Only GC when neither endpoint is actively touching the session.
        # We use sentinel keys "live_active" / "voice_active" — see endpoints.
        if not s.get("live_active") and not s.get("voice_active"):
            _SESSIONS.pop(session_id, None)


def _ensure_weight(dest: pathlib.Path, url: str, expect_bytes: int, label: str) -> bool:
    """Fetch a model weight if it is not already on disk. Returns True if the
    file is usable afterwards.

    Downloads to a `.part` file and renames only once the whole body has
    arrived and its length checks out, so an interrupted boot leaves no
    truncated .onnx behind for the next boot to load and fail on in a much
    more confusing way.
    """
    if dest.exists() and dest.stat().st_size > 0:
        if expect_bytes and dest.stat().st_size != expect_bytes:
            print(f"[LUCY] {label}: on disk but {dest.stat().st_size} bytes, "
                  f"expected {expect_bytes} — re-downloading")
            with contextlib.suppress(OSError):
                dest.unlink()
        else:
            return True
    if not _AUTO_DOWNLOAD:
        print(f"[LUCY] {label} missing and LUCY_AUTO_DOWNLOAD=0 — skipping")
        return False

    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.parent / (dest.name + ".part")
    with contextlib.suppress(OSError):
        part.unlink()
    print(f"[LUCY] downloading {label} → {dest} …", flush=True)
    try:
        # read timeout, not total: these are hundreds of MB and a wall-clock
        # timeout would kill a download that is progressing perfectly well.
        with httpx.stream("GET", url, follow_redirects=True,
                          timeout=httpx.Timeout(30.0, read=180.0)) as r:
            r.raise_for_status()
            total = int(r.headers.get("content-length") or expect_bytes or 0)
            done = 0
            step = max(1, total // 10) if total else 0
            mark = step
            with open(part, "wb") as fh:
                for chunk in r.iter_bytes(1 << 20):
                    fh.write(chunk)
                    done += len(chunk)
                    if step and done >= mark:
                        print(f"[LUCY]   {label}: {done * 100 // total}% "
                              f"({done >> 20}/{total >> 20} MB)", flush=True)
                        mark += step
        if expect_bytes and done != expect_bytes:
            raise IOError(f"got {done} bytes, expected {expect_bytes}")
        part.replace(dest)
        print(f"[LUCY] {label} ready ({done >> 20} MB)", flush=True)
        return True
    except Exception as e:
        with contextlib.suppress(OSError):
            part.unlink()
        print(f"[LUCY] {label} download failed ({type(e).__name__}: {e}) — "
              f"fetch it manually into {dest.parent}")
        return False


def _load_models() -> None:
    """Load InsightFace FaceAnalysis, inswapper (+ emap), and Haar cascade.

    Honors LUCY_MINIMAL_MODE=1 env var: when set, skips ALL GPU model loads
    (inswapper, BiSeNet, Wav2Lip, CodeFormer, GFPGAN, FaceAnalysis). Only
    voice WS (CPU librosa pitch-shift) + demo HTML + avatar serving stay
    alive. This frees ~3-4 GB GPU so InstantID (port 7861) can use the
    full 24 GB on A10G.
    """
    if os.environ.get("LUCY_MINIMAL_MODE") == "1":
        print("[LUCY] MINIMAL_MODE=1 — skipping GPU model loads. "
              "Voice WS + demo HTML + avatar serving only.")
        return
    global _face_app, _face_app_fast, _inswapper, _inswap_emap, _haar_cascade

    # Full pipeline (detection + landmarks + ArcFace + gender/age) — used ONCE
    # per session when the source avatar is loaded so we can extract its
    # 512-d normed_embedding for the inswapper source latent.
    _face_app = FaceAnalysis(name="buffalo_l", providers=["CUDAExecutionProvider", "CPUExecutionProvider"])
    _face_app.prepare(ctx_id=0, det_thresh=0.3, det_size=(640, 640))

    # Per-frame target detection — also high res for accurate keypoints
    # (which determine warp quality). Recognition/genderage stripped because
    # they're truly unused for target frames.
    _face_app_fast = FaceAnalysis(name="buffalo_l", providers=["CUDAExecutionProvider", "CPUExecutionProvider"])
    # Back to 480 detection — at 320 the 106 landmarks were jittery,
    # which broke the expression detail transfer (mouth/brow masks
    # would jump frame to frame). Costs ~15 ms more but landmarks are
    # what makes the swap look alive.
    _face_app_fast.prepare(ctx_id=0, det_thresh=0.3, det_size=(480, 480))
    for mod in ("recognition", "genderage"):
        if mod in _face_app_fast.models:
            del _face_app_fast.models[mod]

    # inswapper_128 ONNX
    import onnxruntime as ort
    sess_opts = ort.SessionOptions()
    sess_opts.graph_optimization_level = ort.GraphOptimizationLevel.ORT_ENABLE_ALL
    _inswapper = ort.InferenceSession(
        _INSWAPPER_PATH,
        sess_options=sess_opts,
        providers=["CUDAExecutionProvider", "CPUExecutionProvider"],
    )

    # CRITICAL: inswapper_128 needs the source embedding mapped through an "emap"
    # (512x512 matrix baked into the ONNX as the last initializer) before passing
    # it as the source latent. Without this step the swap produces garbage / no-op.
    import onnx
    from onnx.numpy_helper import to_array
    _model_proto = onnx.load(_INSWAPPER_PATH)
    _inswap_emap = to_array(_model_proto.graph.initializer[-1]).astype(np.float32)
