def _is_cartoon(img: np.ndarray) -> bool:
    """Heuristic: cartoon/anime images have lower edge density."""
    gray  = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    edges = cv2.Canny(gray, 100, 200)
    density = np.count_nonzero(edges) / edges.size
    return density < 0.04


def _color_transfer(src: np.ndarray, tgt: np.ndarray) -> np.ndarray:
    """Transfer mean+std colour statistics from src to tgt in LAB space."""
    src_lab = cv2.cvtColor(src, cv2.COLOR_BGR2LAB).astype(np.float32)
    tgt_lab = cv2.cvtColor(tgt, cv2.COLOR_BGR2LAB).astype(np.float32)
    for c in range(3):
        sm, ss = src_lab[:, :, c].mean(), src_lab[:, :, c].std()
        tm, ts = tgt_lab[:, :, c].mean(), tgt_lab[:, :, c].std()
        if ts > 1e-6:
            tgt_lab[:, :, c] = (tgt_lab[:, :, c] - tm) * (ss / ts) + sm
    tgt_lab = np.clip(tgt_lab, 0, 255).astype(np.uint8)
    return cv2.cvtColor(tgt_lab, cv2.COLOR_LAB2BGR)


# ─────────────────────────────────────────────────────────────────────────────
#  Swap implementations
# ─────────────────────────────────────────────────────────────────────────────
def _run_inswapper(src_face, tgt_face, tgt_img: np.ndarray) -> np.ndarray:
    """Single inswapper pass — returns the modified target image.

    Inswapper_128 ONNX interface:
      • input 'target': warped target face patch (1, 3, 128, 128) in RGB [0,1]
      • input 'source': source identity embedding (1, 512) — normed
      • output:         modified target face (1, 3, 128, 128) in RGB [0,1]
    We feed the SOURCE face's normed_embedding so the target patch
    inherits the source identity.
    """
    in_names  = [i.name for i in _inswapper.get_inputs()]
    out_names = [o.name for o in _inswapper.get_outputs()]

    # Source latent: embedding @ emap, then L2-normalize. This is the official
    # InsightFace inswapper recipe — without the emap projection the model
    # outputs ~the original face (effectively a no-op swap).
    #
    # IDENTITY BOOST: after normalization we scale the latent by
    # _IDENTITY_BOOST. The inswapper conv stack treats the latent as a
    # style vector; pushing its magnitude > 1 amplifies the identity
    # signal so the output looks more like the source face (at the cost
    # of slightly less natural skin in extreme cross-ethnicity swaps).
    # This is the standard community trick for "stronger swap" without
    # retraining the model.
    src_embed = src_face.normed_embedding.reshape(1, -1).astype(np.float32)
    latent    = src_embed @ _inswap_emap
    latent    = latent / (np.linalg.norm(latent) + 1e-9)
    latent    = latent * _IDENTITY_BOOST
    blob      = latent.astype(np.float32)

    # Warp target face patch to 128×128 ArcFace template
    kps = tgt_face.kps
    M = cv2.estimateAffinePartial2D(kps, _get_arcface_template(128))[0]
    face_patch = cv2.warpAffine(tgt_img, M, (128, 128), flags=cv2.INTER_LINEAR)
    face_patch_f = (face_patch.astype(np.float32) / 255.0)
    face_patch_f = face_patch_f[:, :, ::-1]  # BGR→RGB
    face_patch_f = face_patch_f.transpose(2, 0, 1)[np.newaxis]

    result_patch = _inswapper.run(
        out_names,
        {in_names[0]: face_patch_f, in_names[1]: blob},
    )[0][0]

    result_patch = result_patch.transpose(1, 2, 0)[:, :, ::-1]  # RGB→BGR
    result_patch = (np.clip(result_patch, 0, 1) * 255).astype(np.uint8)

    M_inv = cv2.invertAffineTransform(M)
    patch_back = cv2.warpAffine(result_patch, M_inv, (tgt_img.shape[1], tgt_img.shape[0]),
                                flags=cv2.INTER_CUBIC)

    ih, iw = tgt_img.shape[:2]
    x1, y1, x2, y2 = (int(v) for v in tgt_face.bbox)
    fw, fh = x2 - x1, y2 - y1
    cx, cy = (x1 + x2) // 2, (y1 + y2) // 2

    # Precise face mask from the 106 facial landmarks InsightFace already
    # detected — convex hull = natural face outline (jaw → cheek → temple).
    # Eliminates the obvious 'cut and paste' look an ellipse causes around
    # the chin and jawline. Falls back to the old ellipse only if landmarks
    # aren't available.
    lmk = getattr(tgt_face, "landmark_2d_106", None)
    blend_mask = np.zeros((ih, iw), np.uint8)
    if lmk is not None and len(lmk) > 10:
        pts = lmk.astype(np.int32)
        # Tight hull (1.06). Larger expansions tried earlier (1.15 +
        # chin-downward bias + 25 px feather) created a visible blur
        # halo around the lower face because the wide soft mask
        # blended swap+original pixels over a large strip - the user
        # called it "vovel" (oval). Tight hull + small feather +
        # MIXED_CLONE (below) gives an invisible mask boundary the
        # way wearing a real mask does.
        center = np.array([cx, cy], dtype=np.float32)
        expanded = (pts.astype(np.float32) - center) * _HULL_EXPAND + center
        hull = cv2.convexHull(expanded.astype(np.int32))
        cv2.fillPoly(blend_mask, [hull], 255)
        blend_mask = cv2.GaussianBlur(blend_mask, (15, 15), 0)
        _, blend_mask = cv2.threshold(blend_mask, 100, 255, cv2.THRESH_BINARY)
        M_m = cv2.moments(blend_mask)
        if M_m["m00"] > 0:
            poisson_cx = int(M_m["m10"] / M_m["m00"])
            poisson_cy = int(M_m["m01"] / M_m["m00"])
        else:
            poisson_cx, poisson_cy = cx, cy
    else:
        # Fallback ellipse (forehead-extended) if landmarks missing
        oval_cy = max(1, cy - int(fh * 0.08))
        oval_rx = max(1, int(fw * 0.54))
        oval_ry = max(1, int(fh * 0.62))
        oval_cy = int(np.clip(oval_cy, oval_ry + 1, ih - oval_ry - 1))
        ecx     = int(np.clip(cx,      oval_rx + 1, iw - oval_rx - 1))
        cv2.ellipse(blend_mask, (ecx, oval_cy), (oval_rx, oval_ry), 0, 0, 360, 255, -1)
        poisson_cx, poisson_cy = ecx, oval_cy

    # Poisson seamless clone in MIXED_CLONE mode. MIXED_CLONE picks the
    # stronger gradient between source and target at the boundary so
    # skin texture, lighting and pores carry over from the user's
    # original frame into the swapped region.
    #
    # Crop to a face-bbox ROI before cloning — Poisson cost scales with
    # mask region, and on a 1280×720 frame the full-frame clone was the
    # single biggest per-frame cost. ROI clone is ~3-5x faster with
    # identical visual output (the clone only touches pixels inside
    # blend_mask anyway).
    if _CLONE_MODE == "alpha":
        bm    = cv2.GaussianBlur(blend_mask, (21, 21), 0)
        alpha = bm[:, :, np.newaxis].astype(np.float32) / 255.0
        swapped = (patch_back.astype(np.float32) * alpha +
                   tgt_img.astype(np.float32) * (1 - alpha)).astype(np.uint8)
        return _restore_face(swapped, tgt_face)

    clone_flag = cv2.MIXED_CLONE if _CLONE_MODE == "mixed" else cv2.NORMAL_CLONE
    pad = max(40, (fw + fh) // 8)
    rx1 = max(0, x1 - pad);  ry1 = max(0, y1 - pad)
    rx2 = min(iw, x2 + pad); ry2 = min(ih, y2 + pad)
    roi_w, roi_h = rx2 - rx1, ry2 - ry1
    try:
        if roi_w > 8 and roi_h > 8 and blend_mask[ry1:ry2, rx1:rx2].any():
            src_roi  = patch_back[ry1:ry2, rx1:rx2]
            tgt_roi  = tgt_img[ry1:ry2, rx1:rx2]
            mask_roi = blend_mask[ry1:ry2, rx1:rx2]
            roi_cx = poisson_cx - rx1
            roi_cy = poisson_cy - ry1
            # Centre must stay inside the ROI mask; recompute from ROI mask
            # if the cached centroid landed outside (rare, but Poisson
            # raises cv2.error otherwise).
            if not (0 < roi_cx < roi_w and 0 < roi_cy < roi_h):
                M_r = cv2.moments(mask_roi)
                if M_r["m00"] > 0:
                    roi_cx = int(M_r["m10"] / M_r["m00"])
                    roi_cy = int(M_r["m01"] / M_r["m00"])
                else:
                    roi_cx, roi_cy = roi_w // 2, roi_h // 2
            cloned_roi = cv2.seamlessClone(
                src_roi, tgt_roi, mask_roi, (roi_cx, roi_cy), clone_flag,
            )
            swapped = tgt_img.copy()
            swapped[ry1:ry2, rx1:rx2] = cloned_roi
        else:
            swapped = cv2.seamlessClone(patch_back, tgt_img, blend_mask,
                                        (poisson_cx, poisson_cy), clone_flag)
    except cv2.error:
        bm = cv2.GaussianBlur(blend_mask, (41, 41), 0)
        alpha = bm[:, :, np.newaxis].astype(np.float32) / 255.0
        swapped = (patch_back.astype(np.float32) * alpha +
                   tgt_img.astype(np.float32) * (1 - alpha)).astype(np.uint8)

    return _restore_face(swapped, tgt_face)


def _restore_face(swapped: np.ndarray, tgt_face) -> np.ndarray:
    """CodeFormer restoration on the swapped face — the direct fix for
    inswapper's 128 px softness ceiling. Works at 512 px aligned-to-template
    and restores identity-consistent detail (eyes, lips, pores) on top of the
    paste. weight=0.9 sharpens while locking identity; lower weight smooths so
    aggressively the restored face stops looking like the avatar.

    Replaces the old unsharp mask (amplified noise) and GFPGAN (full frame,
    slow, weight=0.5 erased identity).
    """
    global _CODEFORMER_COUNTER
    if (_codeformer is not None
            and _CODEFORMER_EVERY > 0
            and getattr(tgt_face, "kps", None) is not None
            and (_CODEFORMER_COUNTER % _CODEFORMER_EVERY) == 0):
        try:
            swapped = _codeformer.restore_face(
                swapped, tgt_face.kps, weight=_CF_WEIGHT,
            )
        except Exception:
            pass
    _CODEFORMER_COUNTER += 1
    return swapped


_ARCFACE_DST = np.array([
    [38.2946, 51.6963],
    [73.5318, 51.5014],
    [56.0252, 71.7366],
    [41.5493, 92.3655],
    [70.7299, 92.2041],
], dtype=np.float32)


def _get_arcface_template(size: int) -> np.ndarray:
    scale = size / 112.0
    return _ARCFACE_DST * scale


def _swap_real(src_img: np.ndarray, tgt_img: np.ndarray) -> np.ndarray:
    """
    Real-face swap:
      1. inswapper on face region
      2. SeamlessClone head+hair oval back onto original target
    """
    src_faces = _face_app.get(src_img)
    tgt_faces = _face_app.get(tgt_img)
    src_face  = _largest_face(src_faces)
    tgt_face  = _largest_face(tgt_faces)
    if src_face is None or tgt_face is None:
        raise ValueError("Could not detect face in source or target image")

    # Step 1 — inswapper
    swapped = _run_inswapper(src_face, tgt_face, tgt_img)

    # Step 2 — hair oval seamlessClone to bring hair from swapped→tgt
    hair_mask = _head_fg_mask(swapped, tgt_face.bbox)
    # Centre of mass of mask for seamlessClone
    M = cv2.moments(hair_mask)
    if M["m00"] > 0:
        cX = int(M["m10"] / M["m00"])
        cY = int(M["m01"] / M["m00"])
    else:
        x1, y1, x2, y2 = (int(v) for v in tgt_face.bbox)
        cX, cY = (x1 + x2) // 2, (y1 + y2) // 2
    try:
        result = cv2.seamlessClone(swapped, tgt_img, hair_mask, (cX, cY), cv2.NORMAL_CLONE)
    except cv2.error:
        result = swapped  # fallback: seamlessClone failed, keep inswapper result
    return result


def _swap_geometric(src_img: np.ndarray, tgt_img: np.ndarray) -> np.ndarray:
    """
    Cartoon/anime swap:
      - Strip background corners to avoid artefacts
      - Colour transfer for style adaptation
      - Single seamlessClone with full head+hair mask
    """
    src_faces = _face_app.get(src_img)
    tgt_faces = _face_app.get(tgt_img)
    src_face  = _largest_face(src_faces)
    tgt_face  = _largest_face(tgt_faces)
    if src_face is None or tgt_face is None:
        raise ValueError("Could not detect face in source or target image")

    # Colour-match source to target palette
    src_adapted = _color_transfer(tgt_img, src_img)

    # Resize source to match target face scale
    sx1, sy1, sx2, sy2 = (int(v) for v in src_face.bbox)
    tx1, ty1, tx2, ty2 = (int(v) for v in tgt_face.bbox)
    scale = max((tx2 - tx1) / max(sx2 - sx1, 1), (ty2 - ty1) / max(sy2 - sy1, 1))
    new_w = int(src_img.shape[1] * scale)
    new_h = int(src_img.shape[0] * scale)
    src_resized = cv2.resize(src_adapted, (new_w, new_h), interpolation=cv2.INTER_LANCZOS4)

    # Detect face in resized source
    src_r_faces = _face_app.get(src_resized)
    src_r_face  = _largest_face(src_r_faces)
    if src_r_face is None:
        src_r_face = src_face  # fallback

    # Build composite: paste resized source face region onto target
    canvas = tgt_img.copy()
    sr_x1, sr_y1, sr_x2, sr_y2 = (int(v) for v in src_r_face.bbox)
    patch_w, patch_h = sr_x2 - sr_x1, sr_y2 - sr_y1
    tcx, tcy = (tx1 + tx2) // 2, (ty1 + ty2) // 2
    dst_x1 = max(0, tcx - patch_w // 2)
    dst_y1 = max(0, tcy - patch_h // 2)
    dst_x2 = min(canvas.shape[1], dst_x1 + patch_w)
    dst_y2 = min(canvas.shape[0], dst_y1 + patch_h)
    act_w, act_h = dst_x2 - dst_x1, dst_y2 - dst_y1
    patch = src_resized[sr_y1:sr_y1 + act_h, sr_x1:sr_x1 + act_w]
    canvas[dst_y1:dst_y2, dst_x1:dst_x2] = patch

    # Head+hair mask for seamlessClone
    face_bbox_for_mask = [dst_x1, dst_y1, dst_x2, dst_y2]
    head_mask = _head_fg_mask(canvas, face_bbox_for_mask)
    M = cv2.moments(head_mask)
    if M["m00"] > 0:
        cX = int(M["m10"] / M["m00"])
        cY = int(M["m01"] / M["m00"])
    else:
        cX, cY = tcx, tcy
    try:
        result = cv2.seamlessClone(canvas, tgt_img, head_mask, (cX, cY), cv2.MIXED_CLONE)
    except cv2.error:
        result = canvas
    return result


def _swap(src_img: np.ndarray, tgt_img: np.ndarray) -> np.ndarray:
    """Dispatcher: cartoon → _swap_geometric, real → _swap_real."""
    if _is_cartoon(src_img):
        return _swap_geometric(src_img, tgt_img)
    return _swap_real(src_img, tgt_img)


def _color_correct_face(swapped: np.ndarray, target: np.ndarray, bbox) -> np.ndarray:
    """Reinhard-style LAB-space color transfer: match swapped face's mean/std
    (per channel) to the target face region. Much better skin tone match
    than simple per-channel brightness scaling — preserves saturation
    relationships and handles cross-ethnicity swaps cleanly."""
    x1, y1, x2, y2 = [int(v) for v in bbox]
    x1, y1 = max(0, x1), max(0, y1)
    x2, y2 = min(swapped.shape[1], x2), min(swapped.shape[0], y2)
    if x2 <= x1 or y2 <= y1:
        return swapped
    sw_patch  = swapped[y1:y2, x1:x2]
    tgt_patch = target[y1:y2, x1:x2]
    if sw_patch.size == 0 or tgt_patch.size == 0:
        return swapped

    sw_lab  = cv2.cvtColor(sw_patch,  cv2.COLOR_BGR2LAB).astype(np.float32)
    tgt_lab = cv2.cvtColor(tgt_patch, cv2.COLOR_BGR2LAB).astype(np.float32)
    out = sw_lab.copy()
    # Per-channel blend. Old defaults (0.65, 0.95, 0.95) pulled almost all
    # chroma from the user back into the swap — that's what made cross-
    # ethnicity swaps look like the user with a stranger's eyes. New defaults
    # (LUCY_COLOR_L=0.35, LUCY_COLOR_AB=0.25) keep most of the AVATAR's skin
    # tone visible so the swap actually looks like the avatar. The user can
    # crank these back up via env if they want stronger blend into target
    # lighting (e.g. if studio lights are weird).
    blends = (_COLOR_L, _COLOR_AB, _COLOR_AB)
    for c in range(3):
        sm, ss = sw_lab[:, :, c].mean(),  sw_lab[:, :, c].std() + 1e-6
        tm, ts = tgt_lab[:, :, c].mean(), tgt_lab[:, :, c].std() + 1e-6
        adjusted = (sw_lab[:, :, c] - sm) * (ts / ss) + tm
        out[:, :, c] = blends[c] * adjusted + (1 - blends[c]) * sw_lab[:, :, c]
    out = np.clip(out, 0, 255).astype(np.uint8)
    out_bgr = cv2.cvtColor(out, cv2.COLOR_LAB2BGR)

    result = swapped.copy()
    result[y1:y2, x1:x2] = out_bgr
    return result


def _color_correct_face_hull(swapped: np.ndarray, target: np.ndarray, tgt_face) -> np.ndarray:
    """LAB-space mean/std transfer using the user's actual face hull
    (not bbox) as the sample region.

    Sampling from bbox includes background pixels and can shift the chin
    colour incorrectly. Using the convex hull of the 106 landmarks gives
    skin-only statistics, so chin / jawline blend into the user's neck.

    Falls back to the bbox-based version if landmarks are missing.
    """
    lmk = getattr(tgt_face, "landmark_2d_106", None)
    if lmk is None or len(lmk) < 10:
        return _color_correct_face(swapped, target, tgt_face.bbox)

    h, w = swapped.shape[:2]
    pts  = lmk.astype(np.int32)
    hull = cv2.convexHull(pts)

    hull_mask = np.zeros((h, w), np.uint8)
    cv2.fillPoly(hull_mask, [hull], 255)
    sel = hull_mask > 128
    if int(sel.sum()) < 200:
        return _color_correct_face(swapped, target, tgt_face.bbox)

    sw_lab  = cv2.cvtColor(swapped, cv2.COLOR_BGR2LAB).astype(np.float32)
    tg_lab  = cv2.cvtColor(target,  cv2.COLOR_BGR2LAB).astype(np.float32)

    out_lab = sw_lab.copy()
    # Same knobs as the bbox version. These used to be hard-coded at
    # (0.65, 0.95, 0.95), which pulls nearly all of the user's own chroma
    # back into the swap — the exact effect LUCY_COLOR_AB was introduced to
    # dial down, since it leaves the result looking like the user wearing a
    # stranger's eyes rather than like the uploaded face.
    blends  = (_COLOR_L, _COLOR_AB, _COLOR_AB)
    for c in range(3):
        sm, ss = sw_lab[..., c][sel].mean(), sw_lab[..., c][sel].std() + 1e-6
        tm, ts = tg_lab[..., c][sel].mean(), tg_lab[..., c][sel].std() + 1e-6
        adjusted = (sw_lab[..., c] - sm) * (ts / ss) + tm
        out_lab[..., c] = blends[c] * adjusted + (1 - blends[c]) * sw_lab[..., c]
    out_lab = np.clip(out_lab, 0, 255).astype(np.uint8)
    out_bgr = cv2.cvtColor(out_lab, cv2.COLOR_LAB2BGR)

    # Only apply colour correction inside a softly-feathered hull so the
    # rest of the body (neck, hair) stays untouched.
    alpha = cv2.GaussianBlur(hull_mask, (31, 31), 0).astype(np.float32) / 255.0
    a3    = alpha[:, :, np.newaxis]
    return (out_bgr.astype(np.float32) * a3 +
            swapped.astype(np.float32) * (1.0 - a3)).astype(np.uint8)


def _transfer_expression_detail(swapped: np.ndarray, original: np.ndarray, tgt_face) -> np.ndarray:
    """Layer the user's eye / brow / mouth detail from the ORIGINAL camera
    frame onto the swapped face.

    Why this exists:
      Inswapper is identity-only — its 128 px output smooths out the small
      muscle motion (brow flex, lip-corner pull, eye narrow) that signals
      a live expression. The face starts looking 'static' because all the
      motion cues are gone.

    What it does:
      1. Build a soft mask over mouth + brows + eyes from the 106 landmarks.
      2. Linear blend the original camera pixels into the swapped image
         under that mask. Identity (skin tone, jaw shape) stays from the
         swap; live motion comes from the original.
      3. Mask is generously feathered (31 px Gaussian) so there's no visible
         seam between the swap and the inserted detail.

    Cheap (~3-5 ms on 256 px frames). Skips silently if landmarks missing.
    """
    lmk = getattr(tgt_face, "landmark_2d_106", None)
    if lmk is None or len(lmk) < 106:
        return swapped
    if swapped.shape != original.shape:
        return swapped

    h, w = swapped.shape[:2]
    mask = np.zeros((h, w), np.uint8)

    def fill_hull(idxs):
        try:
            pts = lmk[idxs].astype(np.int32)
            if len(pts) < 3:
                return
            cv2.fillPoly(mask, [cv2.convexHull(pts)], 255)
        except Exception:
            pass

    # Mouth (52..71), brows (43..51, 97..105), eyes (87..96 right, 33..42 left)
    fill_hull(list(range(52, 72)))
    fill_hull(list(range(43, 52)))
    fill_hull(list(range(97, 106)))
    fill_hull(list(range(33, 43)))
    fill_hull(list(range(87, 97)))
    mask = cv2.dilate(mask, np.ones((5, 5), np.uint8), iterations=1)

    if int((mask > 0).sum()) < 200:
        return swapped

    # Strength 0.85 — at 0.55 the muscle motion was barely readable.
    # User explicitly wants "muscle move karta hu but swap face static
    # lagta hai" fixed, so push harder. Identity stays via the swap on
    # the surrounding skin (forehead, cheeks, jaw) which the mask
    # excludes; only the motion-carrying regions get the original.
    alpha = cv2.GaussianBlur(mask, (31, 31), 0).astype(np.float32) / 255.0
    alpha = np.clip(alpha * 0.85, 0.0, 1.0)
    a3    = alpha[:, :, np.newaxis]
    return (original.astype(np.float32) * a3 +
            swapped.astype(np.float32) * (1.0 - a3)).astype(np.uint8)


def _build_face_hull_mask(tgt_face, shape_hw) -> np.ndarray:
    """Reproduce the SAME hull mask used inside _run_inswapper so other
    passes (CodeFormer, etc.) can restrict themselves to the exact same
    boundary. Sharing the boundary is what kills the visible-patch effect:
    if every pass paints to the same edge, there's only one edge."""
    h, w = shape_hw
    mask = np.zeros((h, w), np.uint8)
    lmk = getattr(tgt_face, "landmark_2d_106", None)
    if lmk is None or len(lmk) < 10:
        # Fallback ellipse — same dims as _run_inswapper fallback
        x1, y1, x2, y2 = (int(v) for v in tgt_face.bbox)
        fw, fh = x2 - x1, y2 - y1
        cx, cy = (x1 + x2) // 2, (y1 + y2) // 2
        oval_cy = max(1, cy - int(fh * 0.08))
        oval_rx = max(1, int(fw * 0.54))
        oval_ry = max(1, int(fh * 0.62))
        oval_cy = int(np.clip(oval_cy, oval_ry + 1, h - oval_ry - 1))
        ecx     = int(np.clip(cx,      oval_rx + 1, w - oval_rx - 1))
        cv2.ellipse(mask, (ecx, oval_cy), (oval_rx, oval_ry), 0, 0, 360, 255, -1)
        return mask
    x1, y1, x2, y2 = (int(v) for v in tgt_face.bbox)
    cx, cy = (x1 + x2) // 2, (y1 + y2) // 2
    pts    = lmk.astype(np.int32)
    center = np.array([cx, cy], dtype=np.float32)
    expanded = (pts.astype(np.float32) - center) * 1.06 + center
    hull = cv2.convexHull(expanded.astype(np.int32))
    cv2.fillPoly(mask, [hull], 255)
    mask = cv2.GaussianBlur(mask, (15, 15), 0)
    _, mask = cv2.threshold(mask, 100, 255, cv2.THRESH_BINARY)
    return mask


# 106-landmark indices for InsightFace 2d106det:
#   Mouth outline: 52..71  (20 points around the lips)
#   L brow:        43..51  (9 points)
#   R brow:        97..105 (9 points)
# Using ranges instead of exact ids keeps us robust to off-by-one
# differences across InsightFace versions.
_LMK_MOUTH = list(range(52, 72))
_LMK_LBROW = list(range(43, 52))
_LMK_RBROW = list(range(97, 106))


def _apply_mouth_mask(swapped: np.ndarray, original: np.ndarray, tgt_face) -> np.ndarray:
    """Composite the user's ACTUAL mouth/lip pixels back onto the swap.

    Deep-Live-Cam / iRoopDeepFaceCam technique. Inswapper normally replaces
    the entire face including mouth, which means:
      - Lip movement lags or is interpolated by the model
      - Real-time talking looks "off" because the swap's mouth doesn't
        match what the user is saying
      - Wav2Lip is needed to drive the mouth from audio (laggy, ~30 ms/frame,
        only updates every Nth frame)

    Mouth-masking the original frame back over the swap fixes ALL of this:
      - Lip movement is verbatim the user's, no model needed
      - Real-time lip sync is automatic (frame-rate of the camera)
      - The avatar identity stays everywhere else on the face

    Pipeline:
      1. Get the 20 mouth landmarks from the InsightFace 106-point detector.
      2. Build a convex hull, dilate by _MOUTH_DILATE px so the mask covers
         lips + a thin margin (chin won't be touched).
      3. Gaussian-feather the mask edge so the user's mouth blends into
         the swapped face without a visible seam.
      4. Alpha-blend user's original frame pixels (inside the mask) into
         the swapped frame.
    """
    lmk = getattr(tgt_face, "landmark_2d_106", None)
    if lmk is None or len(lmk) < 72:
        return swapped

    pts = lmk[_LMK_MOUTH].astype(np.int32)
    if len(pts) < 3:
        return swapped

    h, w = swapped.shape[:2]
    mask = np.zeros((h, w), np.uint8)
    hull = cv2.convexHull(pts)
    cv2.fillPoly(mask, [hull], 255)

    # Dilate to cover lip border + slight margin so high-frequency lip
    # edges blend with surrounding swapped cheek pixels.
    if _MOUTH_DILATE > 0:
        k = max(3, _MOUTH_DILATE | 1)
        mask = cv2.dilate(mask, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k)))

    # Soft alpha — Gaussian sigma controls feather softness.
    sigma = max(1, _MOUTH_FEATHER | 1)
    mask = cv2.GaussianBlur(mask, (sigma * 2 + 1, sigma * 2 + 1), 0)
    if int(mask.sum()) < 1000:
        return swapped

    alpha = mask.astype(np.float32) / 255.0
    a3    = alpha[:, :, np.newaxis]
    out   = (original.astype(np.float32) * a3 +
             swapped.astype(np.float32)  * (1.0 - a3)).astype(np.uint8)
    return out


def _smooth_face_kps(prev_face, new_face, weight: float):
    """Exponential moving-average smoothing on kps + landmark_2d_106.

    Reduces inter-frame jitter without adding lag — `weight` is how much
    of the NEW detection to use. weight=1.0 → no smoothing (raw new),
    weight=0.7 → smooth but responsive, weight=0.3 → heavy smoothing
    (laggy if user moves fast).

    CRITICAL: mouth landmarks (52-71) are kept at FULL new weight, never
    smoothed. The mouth mask uses these landmarks to know which pixels
    are "user's mouth" — smoothing them would lag the mouth boundary
    behind real lip motion → visible "lip lag" the user complained
    about. Brow / cheek / eye landmarks ARE smoothed (they don't drive
    the mouth mask and smoothing them kills detection wobble).
    """
    if prev_face is None or new_face is None or weight >= 0.999:
        return new_face
    try:
        new_kps = np.asarray(new_face.kps, dtype=np.float32)
        old_kps = np.asarray(prev_face.kps, dtype=np.float32)
        if new_kps.shape == old_kps.shape:
            new_face.kps = (weight * new_kps + (1 - weight) * old_kps).astype(np.float32)
        new_lmk = getattr(new_face, "landmark_2d_106", None)
        old_lmk = getattr(prev_face, "landmark_2d_106", None)
        if new_lmk is not None and old_lmk is not None and new_lmk.shape == old_lmk.shape:
            blended = (
                weight * new_lmk.astype(np.float32)
                + (1 - weight) * old_lmk.astype(np.float32)
            ).astype(np.float32)
            # Restore the MOUTH region from the raw new detection so lip
            # motion stays real-time. Indices 52..71 = 20 mouth landmarks.
            blended[52:72] = new_lmk[52:72].astype(np.float32)
            new_face.landmark_2d_106 = blended
    except Exception:
        pass  # smoothing is best-effort; raw new_face is fine on error
    return new_face


def _amplify_expression(swapped: np.ndarray, tgt_face) -> np.ndarray:
    """Amplify mouth + brow contrast inside the face hull.

    The inswapper already preserves the user's expression (target patch
    carries the user's mouth/brow shape). But the swap output looks
    smoothed because of the 128px upscale and Poisson clone. This adds
    a soft local contrast boost ONLY inside mouth + brow regions so
    smiles, frowns and brow raises read clearly without changing identity.

    Cheap (~3-5 ms on 384px frames). Skips silently if landmarks missing.
    """
    lmk = getattr(tgt_face, "landmark_2d_106", None)
    if lmk is None or len(lmk) < 106:
        return swapped

    h, w = swapped.shape[:2]

    # Build a soft mask over mouth + brow regions
    mask = np.zeros((h, w), np.uint8)

    def fill_hull(idxs):
        try:
            pts = lmk[idxs].astype(np.int32)
            if len(pts) < 3:
                return
            hull = cv2.convexHull(pts)
            cv2.fillPoly(mask, [hull], 255)
        except Exception:
            pass

    fill_hull(_LMK_MOUTH)
    fill_hull(_LMK_LBROW)
    fill_hull(_LMK_RBROW)
    # Single dilation pass at the end (cheaper than per-region)
    mask = cv2.dilate(mask, np.ones((5, 5), np.uint8), iterations=1)

    if int((mask > 0).sum()) < 200:
        return swapped

    # Soft alpha so the boost fades at the region edges
    alpha = cv2.GaussianBlur(mask, (15, 15), 0).astype(np.float32) / 255.0
    a3    = alpha[:, :, np.newaxis]

    # Local contrast boost via unsharp mask
    blur    = cv2.GaussianBlur(swapped, (0, 0), sigmaX=2.0)
    sharpen = cv2.addWeighted(swapped, 1.6, blur, -0.6, 0)

    out = (sharpen.astype(np.float32) * a3 +
           swapped.astype(np.float32) * (1.0 - a3)).astype(np.uint8)
    return out


def _changed_mask(before: np.ndarray, after: np.ndarray,
                  thresh: int = 12, close_px: int = 9,
                  feather_px: int = 15) -> np.ndarray:
    """A soft mask over the pixels the pipeline actually changed.

    The browser composites the reply onto the live camera through a face-oval
    cut from its own landmarks, which is right for a face-only swap and wrong
    the moment hair is in play: hair sits above the oval, so it would be
    cropped away and the feature would look like it had done nothing.

    Rather than have the client guess at a head-and-hair silhouette, the
    server says exactly which pixels it touched. Differencing output against
    input costs about a millisecond and needs no cooperation from any stage of
    the pipeline, so it stays correct if hair, restoration or anything else is
    added or reordered later.

    The client unions this with its own face oval, which covers the one
    weakness of a difference: interior pixels a swap happened to reproduce
    almost exactly would otherwise punch holes in the mask.
    """
    d = cv2.absdiff(after, before).max(axis=2)
    m = ((d > thresh).astype(np.uint8)) * 255
    k = max(3, close_px | 1)
    m = cv2.morphologyEx(m, cv2.MORPH_CLOSE,
                         cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k)))
    f = max(3, feather_px | 1)
    return cv2.GaussianBlur(m, (f, f), 0)


def _swap_live(src_img: np.ndarray, src_detection, target_img: np.ndarray,
               tgt_face_hint=None,
               src_hair_mask=None, tgt_hair_mask=None,
               smooth_prev=None):
    """
    Fast live swap with cached src_detection.
    Real faces: inswapper + color correction + (optional) BiSeNet hair swap.
    Cartoon:    geometric warp.

    `tgt_face_hint` lets the caller skip per-frame target detection by
    passing the InsightFace Face object from a previous frame.

    `src_hair_mask` (pre-computed once per session) and `tgt_hair_mask`
    (refreshed every few frames) enable HAIR TRANSFER — the avatar's
    hairstyle is warped onto the user's head. Requires _face_parser
    (BiSeNet) to be loaded; if either mask is None, hair swap is skipped
    silently.

    Returns (result_img, tgt_face) — tgt_face is None for cartoon path or
    when no face was detected. Caller can use tgt_face for downstream
    operations (hair transfer, lip sync) without re-detecting.
    """
    src_face, src_kps, src_bbox, src_real = src_detection
    if tgt_face_hint is not None:
        tgt_face = tgt_face_hint
    else:
        # Use the stripped-down detector for per-frame target — ~3x faster
        tgt_faces = _face_app_fast.get(target_img)
        tgt_face  = _largest_face(tgt_faces)
        # Smooth kps + landmarks against previous frame to kill detection
        # jitter. Detection runs every Nth frame; on those frames raw kps
        # can jump 2-5 px even when the face is still, creating visible
        # wobble. EMA smoothing eliminates the wobble at the cost of one
        # frame of "catch-up" latency on fast head motion (invisible at
        # ~6 fps). Tune via LUCY_TRACK_SMOOTH.
        if tgt_face is not None and smooth_prev is not None and _TRACK_SMOOTH < 0.999:
            tgt_face = _smooth_face_kps(smooth_prev, tgt_face, _TRACK_SMOOTH)
    if src_face is None or tgt_face is None:
        return None, None

    if src_real and tgt_face is not None:
        result = _run_inswapper(src_face, tgt_face, target_img)
        result = _color_correct_face_hull(result, target_img, tgt_face)

        # ── Hair transfer (BiSeNet path) ─────────────────────────────────────
        # Warps the avatar's hair onto the user's head using the cached
        # source hair mask + a (refreshed every N frames) target hair mask.
        # face_parser.transfer_hair does all the heavy lifting:
        #   - pre-masks source so no background bleeds
        #   - LAB colour-matches avatar hair to user scene lighting
        #   - excludes the swap face region (so hair never overpaints face)
        # Skipped silently if any input is missing.
        if (_HAIR_SWAP and src_hair_mask is not None
                and getattr(src_face, "kps", None) is not None
                and getattr(tgt_face, "kps", None) is not None):
            try:
                from face_parser import transfer_hair
                # Face exclusion = convex hull of target 106 landmarks
                # (so the swapped face never gets overwritten by hair).
                face_excl = None
                lmk = getattr(tgt_face, "landmark_2d_106", None)
                if lmk is not None and len(lmk) > 10:
                    face_excl = np.zeros(target_img.shape[:2], np.uint8)
                    cv2.fillPoly(face_excl, [cv2.convexHull(lmk.astype(np.int32))], 255)
                # Drop the generous head_region oval — it was clipping AND
                # extending beyond actual hair, creating the rectangular
                # halo. The warped avatar hair mask itself is the right
                # paint region. transfer_hair's internal erode + tight
                # feather (21 px) keeps the edge clean.
                _tgt_hair = tgt_hair_mask if tgt_hair_mask is not None \
                    else np.zeros(target_img.shape[:2], np.uint8)
                result = transfer_hair(
                    src_img, src_hair_mask, src_face.kps,
                    result, _tgt_hair, tgt_face.kps,
                    tgt_face_exclusion_mask=face_excl,
                    tgt_head_region_mask=None,
                    feather_px=21,
                    erode_px=7,
                )
            except Exception as e:
                # Hair swap is best-effort. Any error → keep face-only result.
                print(f"[hair-swap] skipped: {type(e).__name__}: {e}")

        # ── Mouth mask (Deep-Live-Cam technique) ─────────────────────────────
        # Composite the user's actual mouth pixels back over the swap so
        # lip movement is real-time and verbatim. This is what fixes the
        # "lip sync is laggy / wrong" complaint — the user's real mouth
        # is what gets shown, the inswapper face only controls everything
        # ELSE on the face. Wav2Lip downstream can still drive lip-sync
        # from audio when no real mouth is being recorded (eg silent
        # avatar with TTS pipeline) but for live demo this is correct.
        if _MOUTH_MASK:
            try:
                result = _apply_mouth_mask(result, target_img, tgt_face)
            except Exception as e:
                print(f"[mouth-mask] skipped: {type(e).__name__}: {e}")

        return result, tgt_face

    # Cartoon source
    try: return _swap_geometric(src_img, target_img), tgt_face
    except: return None, None


def _do_swap(src_img: np.ndarray, frame: np.ndarray) -> Optional[np.ndarray]:
    """
    Fast swap for WebSocket live path.
    For real faces: inswapper only (no seamlessClone hair pass) for speed.
    For cartoon: full geometric swap.
    """
    if _is_cartoon(src_img):
        try:
            return _swap_geometric(src_img, frame)
        except Exception:
            return None

    src_faces = _face_app.get(src_img)
    tgt_faces = _face_app.get(frame)
    src_face  = _largest_face(src_faces)
    tgt_face  = _largest_face(tgt_faces)
    if src_face is None or tgt_face is None:
        return None
    try:
        return _run_inswapper(src_face, tgt_face, frame)
    except Exception:
        return None


